let active: Language = 'en'

export function setI18nLanguage(language: Language | undefined) {
  active = language === 'ar' ? 'ar' : 'en'
  if (typeof document !== 'undefined') {
    document.documentElement.lang = active
    document.documentElement.dir = active === 'ar' ? 'rtl' : 'ltr'
    document.title = active === 'ar' ? 'Jessica — عالم تعلّم ذكي' : 'Jessica — AI Learning Universe'
  }
}

export function getLanguage(): Language {
  return active
}

function fill(text: string, vars?: Record<string, string | number>) {
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`))
}

/**
 * Translate an English UI string. Preserves the surrounding whitespace that
 * JSX gives us, so wrapping text nodes does not glue words together.
 */
export function tr(text: string, vars?: Record<string, string | number>) {
  if (active === 'en') return fill(text, vars)
  const lead = text.match(/^\s*/)?.[0] ?? ''
  const trail = text.match(/\s*$/)?.[0] ?? ''
  const key = text.replace(/\s+/g, ' ').trim()
  const translated = arabic[key] ?? key
  return lead + fill(translated, vars) + trail
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const language = useApp((s) => s.settings.language)
  setI18nLanguage(language)
  useEffect(() => {
    setI18nLanguage(language)
  }, [language])
  return <Fragment key={language}>{children}</Fragment>
}
