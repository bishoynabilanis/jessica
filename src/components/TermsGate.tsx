import { useState } from 'react'
import { AlertTriangle, BookOpen, Check, Scale, ShieldCheck, Sparkles } from 'lucide-react'
import { Button } from '@/components/ui/Button'
import { Mascot } from '@/components/Mascot'
import { useApp } from '@/store/useApp'
import { TERMS_VERSION } from '@/data/terms'
import { tr } from '@/i18n'
import { cn } from '@/lib/utils'

const POINTS = [
  { icon: BookOpen, title: 'Ministry books belong to the Ministry', text: 'Jessica only links to the official files. Use them for your own study and do not re-upload or share them.' },
  { icon: Scale, title: 'You are responsible for your use', text: 'You agree to follow the law and your school’s rules when you download or import a book.' },
  { icon: AlertTriangle, title: 'AI answers can be wrong', text: 'Explanations and questions are generated by AI. Always check the original page, especially before exams.' },
  { icon: ShieldCheck, title: 'Your data stays on your device', text: 'No account and no server. Your key, books and progress live in this browser.' },
]

export function TermsGate() {
  const acceptTerms = useApp((s) => s.acceptTerms)
  const [checked, setChecked] = useState(false)
  const [refused, setRefused] = useState(false)
  const [expanded, setExpanded] = useState(false)

  return (
    <div className="relative flex min-h-dvh items-center justify-center overflow-hidden px-4 py-8" role="main">
      <div className="pointer-events-none absolute inset-0">
        <div className="absolute left-1/4 top-0 h-[420px] w-[420px] -translate-x-1/2 rounded-full bg-violet-neon/20 blur-[120px]" />
        <div className="absolute bottom-0 right-0 h-[380px] w-[380px] rounded-full bg-aurora-400/15 blur-[120px]" />
      </div>

      <div className="glass relative w-full max-w-2xl overflow-hidden rounded-[32px] border border-line p-5 shadow-card sm:p-7">
        <div className="flex items-center gap-3">
          <Mascot xp={0} size={64} mood="curious" animate={false} />
          <div>
            <p className="text-[9px] font-bold uppercase tracking-[0.22em] text-muted-2">{tr('Before you start')}</p>
            <h1 className="font-display text-xl font-extrabold text-main sm:text-2xl">{tr('Disclaimer & terms of use')}</h1>
          </div>
        </div>

        <p className="mt-3 text-[11px] leading-relaxed text-muted">
          {tr('Please read and accept these terms. They keep Jessica free and independent, and make clear that every learner is responsible for how they use the books and the AI.')}
        </p>

        <div className="mt-4 grid gap-2">
          {POINTS.map((point) => (
            <div key={point.title} className="flex items-start gap-2.5 rounded-2xl border border-line bg-card-2 p-3">
              <span className="grid h-8 w-8 shrink-0 place-items-center rounded-xl bg-aurora-400/10 text-aurora-300">
                <point.icon className="h-4 w-4" />
              </span>
              <div>
                <p className="text-[11px] font-extrabold text-main">{tr(point.title)}</p>
                <p className="mt-0.5 text-[10px] leading-relaxed text-muted">{tr(point.text)}</p>
              </div>
            </div>
          ))}
        </div>

        <button
          onClick={() => setExpanded((value) => !value)}
          className="mt-3 text-[10px] font-bold text-aurora-300 hover:underline"
        >
          {expanded ? tr('Hide the full text') : tr('Read the full disclaimer')}
        </button>

        {expanded && (
          <div className="mt-2 space-y-2 rounded-2xl border border-line bg-card-2 p-3 text-[10px] leading-relaxed text-muted">
            <p>
              {tr('The Egyptian Ministry of Education owns the copyright of its textbooks. Jessica does not host, sell or redistribute these files. The Library only points to links published on the Ministry’s own public servers.')}
            </p>
            <p>
              {tr('If you own the rights to a file and want a link removed, contact us and we will remove it promptly.')}
            </p>
            <p>
              {tr('Jessica is an independent study tool and is not affiliated with or endorsed by the Ministry of Education.')}
            </p>
            <p>
              {tr('Your books, key and progress are stored in this browser only. The app sends requests only to your AI provider, the Ministry file host and the anonymous usage counter if enabled.')}
            </p>
          </div>
        )}

        <label className="mt-4 flex cursor-pointer items-start gap-2.5 rounded-2xl border border-aurora-400/25 bg-aurora-400/5 p-3">
          <button
            type="button"
            role="checkbox"
            aria-checked={checked}
            onClick={() => {
              setChecked((value) => !value)
              setRefused(false)
            }}
            className={cn(
              'mt-0.5 grid h-5 w-5 shrink-0 place-items-center rounded-md border transition',
              checked ? 'border-aurora-400 bg-aurora-400 text-ink-950' : 'border-line-strong bg-white/5 text-transparent',
            )}
          >
            <Check className="h-3.5 w-3.5" />
          </button>
          <span className="text-[10px] leading-relaxed text-main">
            {tr('I have read and accept the disclaimer and terms of use. I understand that I am responsible for how I use official books and for checking AI answers.')}
          </span>
        </label>

        {refused && (
          <p className="mt-2 rounded-xl border border-coral/30 bg-coral/10 p-2.5 text-[10px] leading-relaxed text-coral">
            {tr('You need to accept the terms to use Jessica. Nothing is saved or downloaded until you agree.')}
          </p>
        )}

        <div className="mt-4 flex flex-wrap items-center gap-2">
          <Button
            disabled={!checked}
            onClick={() => acceptTerms(TERMS_VERSION)}
          >
            <Sparkles className="h-4 w-4" /> {tr('Accept and continue')}
          </Button>
          <button
            onClick={() => setRefused(true)}
            className="text-[10px] font-bold text-muted transition hover:text-main"
          >
            {tr('I do not agree')}
          </button>
        </div>
      </div>
    </div>
  )
}
