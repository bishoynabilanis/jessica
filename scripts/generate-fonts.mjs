/**
 * Cairo (SIL Open Font License) is served from this site, not from Google, so
 * visiting a /welcome/ page never sends the visitor's address to a font host.
 * Copies the pinned @fontsource/cairo files into public/welcome/fonts and writes
 * the @font-face rules the pages' style.css imports.
 */
import { copyFileSync, mkdirSync, writeFileSync, existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import { join } from 'node:path'

// `node scripts/generate-fonts.mjs --check` runs last in `npm run content`. It fails the
// build if any public page or generator brings back a Google font link (a visit would
// then send the visitor's address to Google).
if (process.argv.includes('--check')) {
  const bad = []
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const path = join(dir, name)
      if (statSync(path).isDirectory()) walk(path)
      else if (/\.(html|css|mjs)$/.test(name) && name !== 'generate-fonts.mjs' && /fonts\.(googleapis|gstatic)\.com/.test(readFileSync(path, 'utf8'))) bad.push(path)
    }
  }
  walk('public/welcome')
  walk('scripts')
  if (bad.length) {
    console.error(`Google font links found (host Cairo locally instead):\n${bad.join('\n')}`)
    process.exit(1)
  }
  console.log('fonts check: no Google font links')
  process.exit(0)
}

const src = 'node_modules/@fontsource/cairo/files'
const out = 'public/welcome/fonts'
mkdirSync(out, { recursive: true })

// weight asked for by the pages -> file weight we have for each script
const faces = [
  { weight: 400, arabic: 400, latin: 400 },
  { weight: 600, arabic: 600, latin: 700 },
  { weight: 700, arabic: 700, latin: 700 },
  { weight: 800, arabic: 800, latin: 800 },
  { weight: 900, arabic: 900, latin: 900 },
]
const ranges = {
  arabic: 'U+0600-06FF,U+0750-077F,U+0870-088E,U+0890-0891,U+0897-08E1,U+08E3-08FF,U+200C-200E,U+2010-2011,U+204F,U+2E41,U+FB50-FDFF,U+FE70-FE74,U+FE76-FEFC',
  latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
}
const copied = new Set()
let css = '/* generated by scripts/generate-fonts.mjs: Cairo, SIL OFL 1.1, hosted here */\n'
for (const face of faces) {
  for (const script of ['arabic', 'latin']) {
    const file = `cairo-${script}-${face[script]}-normal.woff2`
    if (!existsSync(`${src}/${file}`)) throw new Error(`missing font file ${file}`)
    if (!copied.has(file)) {
      copyFileSync(`${src}/${file}`, `${out}/${file}`)
      copied.add(file)
    }
    css += `@font-face{font-family:'Cairo';font-style:normal;font-display:swap;font-weight:${face.weight};src:url(./${file}) format('woff2');unicode-range:${ranges[script]}}\n`
  }
}
writeFileSync(`${out}/cairo.css`, css)
console.log(`fonts: ${copied.size} files, ${faces.length} weights`)
